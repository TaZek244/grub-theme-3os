GW, GH, GAP = 5, 7, 1


def text_width(text, cell):
    n = len(text)
    return 0 if n == 0 else (n * (GW + GAP) - GAP) * cell


def _blit(ctx, rows, x, y, cell):
    for j, row in enumerate(rows):
        i = 0
        while i < len(row):
            if row[i] == "1":
                k = i
                while k < len(row) and row[k] == "1":
                    k += 1
                ctx.rectangle(x + i * cell, y + j * cell, (k - i) * cell, cell)
                i = k
            else:
                i += 1


def draw_text(ctx, text, x, y, cell, color, shadow=None):
    """Vẽ chữ từ góc trên trái (x, y). color/shadow = (r, g, b[, a]) 0..1; bóng lệch 1 ô xuống-phải."""
    text = text.upper()
    for col, dx in ((shadow, cell), (color, 0)):
        if col is None:
            continue
        ctx.set_source_rgba(*col) if len(col) == 4 else ctx.set_source_rgb(*col)
        cx = x + dx
        for ch in text:
            _blit(ctx, GLYPHS.get(ch, GLYPHS[" "]), cx, y + dx, cell)
            cx += (GW + GAP) * cell
        ctx.fill()


def draw_icon(ctx, name, x, y, cell, color):
    ctx.set_source_rgba(*color) if len(color) == 4 else ctx.set_source_rgb(*color)
    _blit(ctx, ICONS[name], x, y, cell)
    ctx.fill()
